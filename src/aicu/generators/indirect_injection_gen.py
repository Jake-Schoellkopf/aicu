def generate_txt_files(output_dir: Path) -> list[GeneratedFile]:
    """Generate .txt files with embedded injections."""
    files = []
    for payload in INJECTION_PAYLOADS:
        filename = f"{payload['id']}_{payload['name']}.txt"
        files.append(GeneratedFile(
            filename=filename,
            category="indirect_prompt_injection",
            description=payload["description"],
            content=payload["text"].encode("utf-8"),
        ))
    return files


def generate_md_files(output_dir: Path) -> list[GeneratedFile]:
    """Generate .md files with embedded injections."""
    files = []
    for payload in INJECTION_PAYLOADS:
        filename = f"{payload['id']}_{payload['name']}.md"
        md_content = f"# {payload['name'].replace('_', ' ').title()}\n\n{payload['text']}"
        files.append(GeneratedFile(
            filename=filename,
            category="indirect_prompt_injection",
            description=payload["description"],
            content=md_content.encode("utf-8"),
        ))
    return files


def generate_docx_files(output_dir: Path) -> list[GeneratedFile]:
    """Generate minimal .docx files with embedded injections."""
    files = []
    for payload in INJECTION_PAYLOADS:
        filename = f"{payload['id']}_{payload['name']}.docx"
        docx_bytes = _create_minimal_docx(payload["text"])
        files.append(GeneratedFile(
            filename=filename,
            category="indirect_prompt_injection",
            description=payload["description"],
            content=docx_bytes,
        ))
    return files


def _create_minimal_docx(text: str) -> bytes:
    """Create a minimal valid .docx file from text content."""
    import zipfile
    import io

    text_escaped = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    paragraphs = ""
    for line in text_escaped.split("\n"):
        paragraphs += f'<w:p><w:r><w:t xml:space="preserve">{line}</w:t></w:r></w:p>\n'

    document_xml = f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
<w:body>
{paragraphs}
</w:body>
</w:document>'''

    content_types = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>'''

    rels = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>'''

    word_rels = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
</Relationships>'''

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("[Content_Types].xml", content_types)
        zf.writestr("_rels/.rels", rels)
        zf.writestr("word/document.xml", document_xml)
        zf.writestr("word/_rels/document.xml.rels", word_rels)
    return buf.getvalue()


def generate_py_files(output_dir: Path) -> list[GeneratedFile]:
    """Generate .py files with injections hidden in comments and docstrings."""
    files = []
    for payload in INJECTION_PAYLOADS:
        filename = f"{payload['id']}_{payload['name']}.py"
        lines = payload["text"].strip().split("\n")
        py_content = '"""\n' + "\n".join(lines) + '\n"""\n\ndef analyze():\n    pass\n'
        files.append(GeneratedFile(
            filename=filename,
            category="indirect_prompt_injection",
            description=payload["description"],
            content=py_content.encode("utf-8"),
        ))
    return files


def generate_all_indirect_injection_files(output_dir: str | Path) -> list[GeneratedFile]:
    """Generate all indirect prompt injection files."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    all_files = []
    all_files.extend(generate_txt_files(out))
    all_files.extend(generate_md_files(out))
    all_files.extend(generate_docx_files(out))
    all_files.extend(generate_py_files(out))

    for f in all_files:
        (out / f.filename).write_bytes(f.content)
    return all_files
